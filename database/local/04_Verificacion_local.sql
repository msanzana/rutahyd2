-- Comprobaciones de integridad y recuento de tablas para la base LOCAL.
USE rutahyd2_local;
SELECT COUNT(*) AS tablas_totales FROM information_schema.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_TYPE='BASE TABLE';
SELECT TABLE_NAME FROM information_schema.TABLES WHERE TABLE_SCHEMA=DATABASE() ORDER BY TABLE_NAME;
SELECT TABLE_NAME, COLUMN_NAME, REFERENCED_TABLE_NAME, REFERENCED_COLUMN_NAME FROM information_schema.KEY_COLUMN_USAGE WHERE TABLE_SCHEMA=DATABASE() AND REFERENCED_TABLE_NAME IS NOT NULL ORDER BY TABLE_NAME, COLUMN_NAME;
SELECT COUNT(*) AS roles FROM roles;
SELECT COUNT(*) AS bodegas FROM warehouses;
SELECT COUNT(*) AS permisos FROM permissions;
SHOW CREATE TABLE sale_details;
